const LOCK_NOTE = '只统计已在「月度结算单」确认并固定的月份；未固定的月份这里显示为 0。';
const COMMISSION_STEP = '机构抽成：按比例 = 课时费 × 抽成%；固定 = 固定金额；最多不超过课时费。抽成在「机构管理」按课程配置。';
const SETTLE_ORG_STEP = '机构设为「不看金额」（结算给机构）时：整节课时费结算给机构，教师所得记 0，由机构自行发给老师。';

function splitCfg(ctx) {
  return { ...DEFAULT_SPLIT_CONFIG, ...(ctx || {}) };
}

function plain(n) {
  const v = Number(n) || 0;
  return Number.isInteger(v) ? String(v) : String(Math.round(v * 100) / 100);
}

function feeExpr(c) {
  return `${money(c.feeUnit)} × ⌈金额 ÷ ${plain(c.feeStep)}⌉`;
}

function feeRule(c) {
  return `转账手续费 = ${feeExpr(c)}`;
}

function feeExamples(c) {
  const step = Number(c.feeStep) || 0;
  if (!step) return [];
  return [step, step + 0.01, step * 2.4].map((v) => `转 ${money(v)} → 手续费 ${money(transferFee(v, c))}`);
}

